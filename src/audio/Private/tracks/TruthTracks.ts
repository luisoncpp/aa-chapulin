//                                 mid register with silence around it, and one high
//                                 note rings alone as a glint.
//   S2 (bars 5-8)   G G# A Bb     G / E/G# / Am / Bb - first full triads, 8th-note
//                                 line, one breath per bar, peaks climbing to F6.
